import assert from 'node:assert/strict';
import {continueCopilotNavigation,waitForCopilotReady,hasCopilotEmbedControls,matchesCopilotDestination} from '../src/utils/copilotNavigation.js';
assert(matchesCopilotDestination('/app/home','/app'));
assert(!matchesCopilotDestination('/app/customer','/app'));
assert(!matchesCopilotDestination('/app/home','/app/customer'));
assert(matchesCopilotDestination('/object/opportunity/abc','/object/opportunity/abc?viewId=view-1'));
assert(!matchesCopilotDestination('/object/opportunity/other','/object/opportunity/abc?viewId=view-1'));
assert(!matchesCopilotDestination('/objects/opportunities','/objects/opportunities?viewId=view-1'));
assert(!matchesCopilotDestination('/object/opportunity/abc','/object/opportunity/abc?viewId=view-1&other=1'));
const catalog={screens:[{id:'crm',route:'/crm'},{id:'erp',route:'/erp'}]};
const proposal=action=>({proposal:{actions:[action]}});
const start=proposal({type:'navigate',screen:'crm'});
const path={type:'embed_navigate',screen:'crm',path:'/objects/opportunities'};
const creation={type:'embed_open_form',screen:'crm',label:'New Opportunity'};
let navigations=[],proposals=[proposal(path),proposal(creation)];
let result=await continueCopilotNavigation({session:start,catalog,navigate:async a=>navigations.push(a),inspect:async()=>({catalog}),propose:async()=>proposals.shift()});
assert.equal(navigations.length,2);assert.deepEqual(result.session.proposal.actions,[creation],'Creation stops for explicit review, never automatically executes');
for(const type of ['fill','embed_fill','screen_fill','agent_call','agent_chat','watch_connector','embed_open_form']){
  result=await continueCopilotNavigation({session:proposal({type}),catalog,navigate:async()=>assert.fail('Writes/calls are not navigation'),inspect:async()=>assert.fail(),propose:async()=>assert.fail()});
  assert.equal(result.session.proposal.actions[0].type,type);
}
navigations=[];
result=await continueCopilotNavigation({session:start,catalog,navigate:async a=>navigations.push(a),inspect:async()=>({catalog}),propose:async()=>start});
assert.equal(navigations.length,1);assert.equal(result.stopped,true,'Repeated navigation stops instead of looping');
await assert.rejects(()=>continueCopilotNavigation({session:start,catalog,isCurrent:()=>false}),/context changed/);
await assert.rejects(()=>continueCopilotNavigation({session:start,catalog:{screens:[]}}),/access/);
await assert.rejects(()=>continueCopilotNavigation({session:start,catalog,navigate:async()=>{},inspect:async()=>{throw Error('Not loaded');},propose:async()=>assert.fail()}),/Not loaded/);
console.log('PASS Copilot navigation: actual screen opening, fresh inspection, bounded continuation, permission/context checks and creation/write separation.');
let clock=0,reads=0;
const timing={now:()=>clock,sleep:async ms=>{clock+=ms;}};
const ready={path:'/object/example/123',fields:['name']};
assert.deepEqual(await waitForCopilotReady({...timing,inspect:async()=>{reads++;if(clock<8000)throw Error('Frame not registered');if(clock<12000)return {path:'/loading',fields:[]};return ready;},accept:hasCopilotEmbedControls}),ready);
assert.equal(clock,12000,'Waits beyond the old three-second limit for real controls');
clock=0;let writes=0;
await assert.rejects(()=>waitForCopilotReady({...timing,timeoutMs:2000,inspect:async()=>null}),/still loading/);
assert.equal(clock,2000);assert.equal(writes,0,'Readiness never replays a write');
clock=0;let current=true;
await assert.rejects(()=>waitForCopilotReady({...timing,isCurrent:()=>current,inspect:async()=>{current=false;return ready;}}),/context changed/);
clock=0;reads=0;
assert.equal((await waitForCopilotReady({...timing,inspect:async()=>{if(++reads===1)return {path:'/old',fields:['name']};if(reads===2)throw Error('Reload');return ready;},accept:m=>hasCopilotEmbedControls(m)&&m.path===ready.path})).path,ready.path);
assert.equal(reads,3,'Does not accept the old page and survives a reload');
clock=0;
await assert.rejects(()=>waitForCopilotReady({...timing,timeoutMs:2000,inspect:async()=>{clock+=3000;return ready;}}),/still loading/,'Late inspection is not used to continue a task');
console.log('PASS readiness: delayed registration, empty loading DOM, reload, destination check, bounded timeout and actor cancellation.');
clock=0;reads=0;
const fullRecord={path:'/object/example/new',fields:['name','amount','currency'],navigation:[]};
const observedSequence=[{path:fullRecord.path,fields:[],navigation:[{path:'/objects/examples',label:'Examples'}]},{...fullRecord,fields:['name']},fullRecord,fullRecord];
assert.deepEqual(await waitForCopilotReady({...timing,stableSamples:2,inspect:async()=>observedSequence[Math.min(reads++,3)],accept:m=>m?.fields?.length>0}),fullRecord);
assert.equal(reads,4,'A record route and sidebar are not a loaded form; partial field metadata must settle');
console.log('PASS post-creation readiness: reject sidebar-only metadata and require stable form fields before model continuation.');
clock=0;reads=0;
const stableTransport=await waitForCopilotReady({...timing,stableSamples:2,inspect:async()=>({...fullRecord,request:'transport-'+(++reads)})});
assert.equal(reads,2);assert.equal(stableTransport.request,'transport-2','Transport IDs must not affect DOM stability');
