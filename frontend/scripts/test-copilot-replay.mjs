import assert from 'node:assert/strict';
import {replayStep,replayMatches,replayPrompt,openReplayDestination} from '../src/utils/copilotReplay.js';
const recipe={title:'Customer flow',status:'published',version:3,steps:[{screen:'crm',path:'/object/company/:record',instruction:'Inspect name',success:'Name is correct'}]};
assert.equal(replayStep(recipe,3,0),recipe.steps[0]);
assert.throws(()=>replayStep(recipe,2,0));
assert.throws(()=>replayStep({...recipe,status:'archived'},3,0));
assert.throws(()=>replayStep(recipe,3,1));
assert(replayMatches(recipe.steps[0],'/object/company/test-123?viewId=123'));
assert(!replayMatches(recipe.steps[0],'/object/person/test-123'));
assert(!replayMatches(recipe.steps[0],'https://other.example/object/company/test-123'));
assert(replayPrompt(recipe,0).includes('do not save, create or submit'));
console.log('PASS guided replay: publication/version checks, placeholder matching, no values/selectors or write replay.');
let current='/home',actions=[],observed={path:'/app/home',navigation:[{path:'/app/customer',label:'Customer'}]};
const wait=async({inspect,accept,isCurrent})=>{assert(isCurrent());const result=await inspect();assert(accept(result));return result;};
const deps={currentPath:()=>current,navigate:async path=>{actions.push(path);current=path;},inspect:async()=>observed,navigateEmbedded:async path=>{actions.push(path);observed={path,fields:['name']};},wait};
await openReplayDestination({...deps,step:{screen:'master-data',path:'/master-data'},screen:{id:'master-data',route:'/master-data'}});
assert.equal(current,'/master-data');assert.deepEqual(actions,['/master-data']);
await openReplayDestination({...deps,step:{screen:'erp',path:'/app/customer'},screen:{id:'erp',route:'/erp'}});
assert.deepEqual(actions,['/master-data','/erp','/app/customer']);
const before=actions.length;
await assert.rejects(()=>openReplayDestination({...deps,step:{screen:'erp',path:'/app/unseen'},screen:{id:'erp',route:'/erp'}}),/not uniquely visible/);
assert.equal(actions.length,before,'Unobserved links never execute');
await assert.rejects(()=>openReplayDestination({...deps,step:{screen:'erp',path:'/app/customer'},screen:null}),/no longer available/);
await assert.rejects(()=>openReplayDestination({...deps,step:{screen:'erp',path:'/app/customer'},screen:{id:'erp',route:'/erp'},isCurrent:()=>false}),/context changed/);
console.log('PASS replay performs authorized shell and observed embedded navigation, waits for destination, and rejects unseen links and actor changes.');
