import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { knowledgeStore } from '../src/services/knowledge-store.js';
import { resolveKnowledgeAgent } from '../src/services/knowledge-agent-access.js';
const agents=[{id:'agent-a',openclaw_id:'agent-a'}];
assert.equal(resolveKnowledgeAgent('alice','agent-a',{agents}),'agent-a');
assert.equal(resolveKnowledgeAgent('alice','t-alice--agent-a',{agents}),'agent-a');
assert.throws(()=>resolveKnowledgeAgent('alice','t-bob--agent-a',{agents}),/owner mismatch/);
assert.throws(()=>resolveKnowledgeAgent('alice','unknown',{agents}),/not found/);
const db=new Database(':memory:'),store=knowledgeStore(db);
const source=store.save('alice',{name:'Private',kind:'knowledge',collections:['documents']});
assert.deepEqual(store.agentSources('alice','agent-a'),[]);
store.setAgentSources('alice','agent-a',[source.id]);
assert.deepEqual(store.agentSources('alice','agent-a'),[source.id]);
assert.deepEqual(store.agentSources('alice','agent-b'),[]);
assert.deepEqual(store.agentSources('bob','agent-a'),[]);
assert.throws(()=>store.setAgentSources('bob','agent-a',[source.id]),/belonging/);
store.setAgentSources('alice','agent-a',[]);
assert.deepEqual(store.agentSources('alice','agent-a'),[]);
db.close();
console.log('Knowledge agent grants: explicit default deny, agent/company identity, isolation and revoke passed.');
