import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { COPILOT_FORMS, cleanFormPatch, validateCopilotProposal } from '../src/services/ui-copilot-contract.js';
import { uiCopilotStore } from '../src/services/ui-copilot-store.js';
import { syncPlatformHelpCopilot } from '../src/services/platform-help-template-sync.js';
import { mkdtempSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const db=new Database(':memory:');
const store=uiCopilotStore(db);
const a=store.create('company-a','human-a',{status:'active',drafts:{}});
assert.throws(()=>store.get('company-b','human-a',a.id),/not found/);
assert.throws(()=>store.get('company-a','human-b',a.id),/not found/);
const saved=store.update('company-a','human-a',a.id,a.version,{status:'paused',drafts:{}});
assert.equal(saved.version,2);
assert.throws(()=>store.update('company-a','human-a',a.id,1,{status:'active'}),/changed/);
assert.equal(uiCopilotStore(db).get('company-a','human-a',a.id).status,'paused');
db.prepare('UPDATE ui_copilot_sessions SET expires_at=0 WHERE id=?').run(a.id);
assert.throws(()=>store.get('company-a','human-a',a.id),/expired/);
assert.equal(store.latest('company-a','human-a'),undefined);
assert.deepEqual(cleanFormPatch('hire_employee',{name:'Researcher',department:'Research'}),{name:'Researcher',department:'Research'});
for(const invalid of [{password:'secret'},{owner:'other'},{is_orchestrator:true},JSON.parse('{"__proto__":{}}')])assert.throws(()=>cleanFormPatch('hire_employee',invalid));
assert.throws(()=>cleanFormPatch('knowledge_source',{interval_seconds:1}));
assert.throws(()=>cleanFormPatch('knowledge_source',{kind:'arbitrary-http'}));
assert.throws(()=>cleanFormPatch('knowledge_source',{enabled:'true'}));
assert.throws(()=>cleanFormPatch('knowledge_source',{collections:['secrets']}));
const catalog={forms:COPILOT_FORMS,screens:[{id:'home',route:'/'}],agents:[{id:'my-agent'}]};
assert.deepEqual(validateCopilotProposal({message:'Review',actions:[{type:'navigate',screen:'home',route:'https://evil.test'}]},catalog).actions,[{type:'navigate',screen:'home',route:'/'}]);
for(const action of [{type:'execute',code:'fetch(secret)'},{type:'agent_chat',agent:'other-tenant-agent'},{type:'navigate',screen:'admin'},{type:'fill',form:'hire_employee',values:{tools:['shell']}}])assert.throws(()=>validateCopilotProposal({message:'Do it',actions:[action]},catalog));
assert.throws(()=>validateCopilotProposal({message:'Do it',actions:[{type:'fill',form:'hire_employee',values:{name:'Example'}}]},{...catalog,forms:{}}));
assert.equal(validateCopilotProposal({message:'Review',actions:[{type:'agent_chat',agent:'my-agent'}]},catalog).actions[0].route,'/agents/my-agent/chat');
db.close();
const workspace=mkdtempSync(join(tmpdir(),'flolah-copilot-test-'));
try {
  writeFileSync(join(workspace,'AGENTS.md'),'# Tenant instructions\nKeep my custom policy.');
  writeFileSync(join(workspace,'MEMORY.md'),'Tenant memory must survive');
  const template=resolve('../openclaw-workspace-templates/platformhelp');
  assert.equal(syncPlatformHelpCopilot(template,workspace),true);
  const once=readFileSync(join(workspace,'AGENTS.md'),'utf8');
  assert(once.startsWith('# Tenant instructions\nKeep my custom policy.'));
  assert(once.includes('Platform Help UI Copilot operating contract'));
  syncPlatformHelpCopilot(template,workspace);
  assert.equal(readFileSync(join(workspace,'AGENTS.md'),'utf8'),once);
  assert.equal(readFileSync(join(workspace,'MEMORY.md'),'utf8'),'Tenant memory must survive');
  writeFileSync(join(workspace,'TOOLS.md'),'<!-- FLOLAH-PLATFORM-HELP-COPILOT:START -->\nCustom text');
  assert.throws(()=>syncPlatformHelpCopilot(template,workspace),/Malformed/);
  assert(readFileSync(join(workspace,'TOOLS.md'),'utf8').endsWith('Custom text'));
} finally { rmSync(workspace,{recursive:true,force:true}); }
console.log('PASS UI copilot: tenant/actor isolation, durable state, expiry, optimistic concurrency, field contracts, route and agent allowlists.');
console.log('PASS Platform Help template updates: managed guidance, idempotency, tenant notes and memory preservation.');
