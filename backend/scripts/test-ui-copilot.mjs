import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { COPILOT_FORMS, cleanFormPatch, validateCopilotProposal } from '../src/services/ui-copilot-contract.js';
import { uiCopilotStore } from '../src/services/ui-copilot-store.js';
import { copilotFillReceipt } from '../src/services/ui-copilot-progress.js';
import { syncPlatformHelpCopilot } from '../src/services/platform-help-template-sync.js';
import { mkdtempSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const db=new Database(':memory:');
const store=uiCopilotStore(db);
const a=store.create('company-a','human-a',{status:'active',drafts:{}});
assert.throws(()=>store.get('company-b','human-a',a.id),/not found/);
assert.throws(()=>store.get('company-a','human-b',a.id),/not found/);
const saved=store.update('company-a','human-a',a.id,a.version,{status:'paused',drafts:{}});
assert.equal(saved.version,2);
assert.throws(()=>store.update('company-a','human-a',a.id,1,{status:'active'}),/changed/);
assert.equal(uiCopilotStore(db).get('company-a','human-a',a.id).status,'paused');
db.prepare('UPDATE ui_copilot_sessions SET expires_at=0 WHERE id=?').run(a.id);
assert.throws(()=>store.get('company-a','human-a',a.id),/expired/);
assert.equal(store.latest('company-a','human-a'),undefined);
assert.deepEqual(cleanFormPatch('hire_employee',{name:'Researcher',department:'Research'}),{name:'Researcher',department:'Research'});
assert.deepEqual(cleanFormPatch('user_profile',{display_timezone:'Asia/Singapore'}),{display_timezone:'Asia/Singapore'});
assert.throws(()=>cleanFormPatch('user_profile',{display_timezone:'Not/AZone'}),/timezone/);
assert.throws(()=>cleanFormPatch('user_profile',{new_password:'forbidden'}),/Unregistered/);
assert.throws(()=>cleanFormPatch('knowledge_document',{file:'/private/file'}),/Unregistered/);
assert.deepEqual(cleanFormPatch('knowledge_table',{name:'Demo',columns:'name, value'}),{name:'Demo',columns:'name, value'});
for(const invalid of [{password:'secret'},{owner:'other'},{is_orchestrator:true},JSON.parse('{"__proto__":{}}')])assert.throws(()=>cleanFormPatch('hire_employee',invalid));
assert.throws(()=>cleanFormPatch('knowledge_source',{interval_seconds:1}));
assert.throws(()=>cleanFormPatch('knowledge_source',{kind:'arbitrary-http'}));
assert.throws(()=>cleanFormPatch('knowledge_source',{enabled:'true'}));
assert.throws(()=>cleanFormPatch('knowledge_source',{collections:['secrets']}));
const catalog={forms:COPILOT_FORMS,screens:[{id:'home',route:'/'}],agents:[{id:'my-agent'}]};
const progressState={status:'active',proposal:{message:'Review',actions:[{type:'fill',form:'hire_employee',values:{name:'Demo researcher',role:'Research analyst'}}]}};
const receiptInput={type:'fill',form:'hire_employee',values:{name:'Demo researcher'}};
const receipt=copilotFillReceipt(progressState,receiptInput,catalog);
assert.equal(receipt.saved,false);
assert.equal(receipt.status,'entered_client_reported');
assert.deepEqual(receipt.values,{name:'Demo researcher'});
assert.throws(()=>copilotFillReceipt(progressState,{...receiptInput,values:{name:'Forged'}},catalog),/match/);
assert.throws(()=>copilotFillReceipt(progressState,{...receiptInput,values:{}},catalog),/Invalid/);
assert.throws(()=>copilotFillReceipt({...progressState,status:'paused'},receiptInput,catalog),/Resume/);
assert.throws(()=>copilotFillReceipt(progressState,receiptInput,{...catalog,forms:{}}));
const split=[{type:'fill',form:'hire_employee',values:{name:'Demo researcher'}},{type:'fill',form:'hire_employee',values:{role:'Research analyst'}}];
assert.deepEqual(validateCopilotProposal({message:'Review',actions:split},catalog).actions,[{type:'fill',form:'hire_employee',values:{name:'Demo researcher',role:'Research analyst'}}]);
assert.equal(validateCopilotProposal({message:'Review',actions:[split[0],{type:'navigate',screen:'home'},split[1]]},catalog).actions.length,3,'Do not reorder across navigation');
assert.throws(()=>validateCopilotProposal({message:'Review',actions:[split[0],{...split[0],values:{name:'Different name'}}]},catalog),/Conflicting/);
assert.deepEqual(split[0].values,{name:'Demo researcher'},'Grouping must not mutate input');
assert.equal(validateCopilotProposal({message:'Guide',actions:[{type:'guide',form:'user_profile',steps:[{field:'name',instruction:'Enter your display name.'}]}]},catalog).actions[0].steps[0].field,'name');
assert.throws(()=>validateCopilotProposal({message:'Guide',actions:[{type:'guide',form:'user_profile',steps:[{field:'password',instruction:'Enter a password.'}]}]},catalog),/guidance field/);
assert.throws(()=>validateCopilotProposal({message:'Guide',actions:[{type:'guide',form:'user_profile',steps:[]}]},catalog),/guidance steps/);
assert.equal(validateCopilotProposal({message:'Open',actions:[{type:'agent_chat',agent:'my-agent',message:''}]},catalog).actions[0].message,'');
assert.deepEqual(validateCopilotProposal({message:'Review',actions:[{type:'navigate',screen:'home',route:'https://evil.test'}]},catalog).actions,[{type:'navigate',screen:'home',route:'/'}]);
for(const action of [{type:'execute',code:'fetch(secret)'},{type:'agent_chat',agent:'other-tenant-agent'},{type:'navigate',screen:'admin'},{type:'fill',form:'hire_employee',values:{tools:['shell']}}])assert.throws(()=>validateCopilotProposal({message:'Do it',actions:[action]},catalog));
assert.throws(()=>validateCopilotProposal({message:'Do it',actions:[{type:'fill',form:'hire_employee',values:{name:'Example'}}]},{...catalog,forms:{}}));
assert.throws(()=>validateCopilotProposal({message:'Review',actions:[{type:'agent_chat',agent:'my-agent'}]},catalog),/must include message/);
assert.equal(validateCopilotProposal({message:'Review',actions:[{type:'agent_chat',agent:'my-agent',message:'Exact draft'}]},catalog).actions[0].message,'Exact draft');
assert.equal(validateCopilotProposal({message:'Open',actions:[{type:'agent_chat',agent:'my-agent',message:''}]},catalog).actions[0].route,'/agents/my-agent/chat');
assert.equal(validateCopilotProposal({message:'Call',actions:[{type:'agent_call',agent:'my-agent'}]},catalog).actions[0].agent,'my-agent');
assert.throws(()=>cleanFormPatch('broadcast_draft',{recipients:['other-tenant']}),/Unregistered/);
assert.throws(()=>cleanFormPatch('scheduled_goal',{time_local:'25:61'}),/schedule time/);
assert.throws(()=>cleanFormPatch('scheduled_goal',{enabled:true}),/Unregistered/);
assert.throws(()=>cleanFormPatch('objective_draft',{budget_amount:999}),/Unregistered/);
assert.equal(cleanFormPatch('objective_draft',{currency:'USD'}).currency,'USD');
assert.throws(()=>cleanFormPatch('objective_draft',{currency:'ZZZ'}),/currency/);
assert.deepEqual(cleanFormPatch('scheduled_goal',{cadence:'weekly',weekday:2,time_local:'09:30'}),{cadence:'weekly',weekday:2,time_local:'09:30'});
db.close();
const workspace=mkdtempSync(join(tmpdir(),'flolah-copilot-test-'));
try {
  writeFileSync(join(workspace,'AGENTS.md'),'# Tenant instructions\nKeep my custom policy.');
  writeFileSync(join(workspace,'MEMORY.md'),'Tenant memory must survive');
  const template=resolve('../openclaw-workspace-templates/platformhelp');
  assert.equal(syncPlatformHelpCopilot(template,workspace),true);
  const once=readFileSync(join(workspace,'AGENTS.md'),'utf8');
  assert(once.startsWith('# Tenant instructions\nKeep my custom policy.'));
  assert(once.includes('Platform Help UI Copilot operating contract'));
  syncPlatformHelpCopilot(template,workspace);
  assert.equal(readFileSync(join(workspace,'AGENTS.md'),'utf8'),once);
  assert.equal(readFileSync(join(workspace,'MEMORY.md'),'utf8'),'Tenant memory must survive');
  writeFileSync(join(workspace,'TOOLS.md'),'<!-- FLOLAH-PLATFORM-HELP-COPILOT:START -->\nCustom text');
  assert.throws(()=>syncPlatformHelpCopilot(template,workspace),/Malformed/);
  assert(readFileSync(join(workspace,'TOOLS.md'),'utf8').endsWith('Custom text'));
} finally { rmSync(workspace,{recursive:true,force:true}); }
console.log('PASS UI copilot: tenant/actor isolation, durable state, expiry, optimistic concurrency, field contracts, route and agent allowlists.');
console.log('PASS Platform Help template updates: managed guidance, idempotency, tenant notes and memory preservation.');
