import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {adaptCompleteToolDirectory} from '../../deploy/scripts/install-native-complete-tool-directory.mjs';
const root='/usr/local/lib/node_modules/openclaw/dist';
const file=readdirSync(root).find(n=>/^local-model-lean-/.test(n)&&readFileSync(root+'/'+n,'utf8').includes('function formatToolSearchCatalogDirectory('));
const source=readFileSync(root+'/'+file,'utf8');
assert.equal(adaptCompleteToolDirectory(source),source,'installation is idempotent');
assert.throws(()=>adaptCompleteToolDirectory('unknown runtime'),/Unsupported/);
const {c:compact,l:controls,x:ref,d:directory}=await import(root+'/'+file);
const config={tools:{toolSearch:{enabled:true,mode:'tools'}}};
const catalogRef=ref();let dispatched=0;
const names=Array.from({length:210},(_,i)=>'fixture_capability_'+String(i).padStart(3,'0'));
const tools=names.map(name=>({name,label:name,description:'Full exact authoritative capability description '.repeat(8),parameters:{type:'object',properties:{}},execute:async()=>{dispatched++;return {content:[]};}}));
compact({config,catalogRef,tools:[...controls({config,catalogRef}),...tools]});
const prompt=directory({config,catalogRef});
assert(prompt.length<=18000);
for(const name of names)assert(prompt.includes('- '+name+' '),'authorized name retained: '+name);
assert(!prompt.includes('additional tools omitted'));
assert(!prompt.includes('foreign_ungranted_capability'));
assert.equal(dispatched,0);
console.log('COMPLETE_TOOL_DIRECTORY_TEST_OK: 210 authorized names retained under 18k; no dispatch or grant expansion');
