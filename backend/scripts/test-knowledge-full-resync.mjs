import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import {knowledgeStore} from '../src/services/knowledge-store.js';
const db=new Database(':memory:'),store=knowledgeStore(db);
const source=store.save('owner',{name:'Rebuild',kind:'content',collections:['generated']});
store.enqueue('owner',source.id);const initial=store.claim();
store.saveIncrementalRecord(initial,'a','hash',1);
store.finish(initial,'g:1');
store.setExcluded('owner',source.id,'excluded',true);
store.setAgentSources('owner','agent',[source.id]);
assert.throws(()=>store.fullResync('other',source.id),/not found/);
const job=store.fullResync('owner',source.id);
assert.equal(job.trigger,'full_resync');
assert.equal(store.get('owner',source.id).revision,'g:1');
assert.equal(store.excluded('owner',source.id,'excluded'),true);
assert.deepEqual(store.agentSources('owner','agent'),[source.id]);
assert.equal(db.prepare('SELECT count(*) AS n FROM knowledge_incremental_records').get().n,0);
assert.throws(()=>store.fullResync('owner',source.id),/existing synchronization/);
const rebuild=store.claim();store.finish(rebuild,'g:2');
assert.equal(store.get('owner',source.id).revision,'g:2');
store.setEnabled('owner',source.id,false);
assert.throws(()=>store.fullResync('owner',source.id),/Resume/);
console.log('Full resync: owner isolation, overlap rejection, published revision preservation, exclusions and grants passed.');
