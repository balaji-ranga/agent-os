import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { createSteeringStore, steeringPrompt } from '../src/services/work-steering.js';
const db = new Database(':memory:');
db.exec(`
CREATE TABLE chat_work_units(id TEXT,owner_user_id TEXT,agent_id TEXT,status TEXT,execution_mode TEXT,resolved_request TEXT,created_at TEXT);
CREATE TABLE agent_goal_runs(id TEXT,owner_user_id TEXT,agent_id TEXT,status TEXT,title TEXT,created_at TEXT);
CREATE TABLE agent_delegation_tasks(id INTEGER,owner_user_id TEXT,to_agent_id TEXT,status TEXT,prompt TEXT,created_at TEXT);
CREATE TABLE scheduled_goals(id TEXT,owner_user_id TEXT,agent_id TEXT,status TEXT,title TEXT,created_at TEXT);
CREATE TABLE scheduled_goal_runs(id TEXT,goal_id TEXT,owner_user_id TEXT,agent_id TEXT,status TEXT,created_at TEXT);
INSERT INTO chat_work_units VALUES('chat1','ownerA','coo','active','chat','Research','2026-10-10');
INSERT INTO agent_goal_runs VALUES('goal1','ownerA','coo','running','Goal','2026-10-10'),('ended','ownerA','coo','completed','Done','2026-10-10'),('goal2','ownerB','coo','running','Private','2026-10-10');
INSERT INTO agent_delegation_tasks VALUES(1,'ownerA','research','pending','Research task','2026-10-10');
INSERT INTO scheduled_goals VALUES('sg1','ownerA','coo','active','Digest','2026-10-10');
INSERT INTO scheduled_goal_runs VALUES('sgr1','sg1','ownerA','coo','running','2026-10-10');
`);
let store = createSteeringStore(db);
assert.equal(store.listTargets('ownerA').length, 5);
assert.equal(store.listTargets('ownerA','research').length, 1);
assert.ok(store.listTargets('ownerA').every(r => r.id !== 'goal2'));
db.prepare("INSERT INTO chat_work_units VALUES('stale-chat','ownerA','coo','active','chat','Old work','2026-10-10')").run();
const exactChat = createSteeringStore(db, { chatActive: (_agent, _owner, id) => id === 'chat1' });
assert.equal(exactChat.listTargets('ownerA').filter(r => r.kind === 'chat').length, 1);
assert.throws(() => exactChat.enqueue('ownerA','ownerA',{target_kind:'chat',target_id:'stale-chat',message:'Not for current turn',idempotency_key:'stale-chat-test'}), /no longer/);
db.prepare("DELETE FROM chat_work_units WHERE id='stale-chat'").run();
const body = { target_kind: 'goal', target_id: 'goal1', message: 'Cite primary sources', idempotency_key: 'retry-key-1' };
const note = store.enqueue('ownerA','ownerA',body);
assert.equal(note.status, 'queued');
assert.equal(db.prepare('SELECT status FROM agent_goal_runs WHERE id=?').get('goal1').status, 'running');
assert.equal(db.prepare('SELECT count(*) n FROM agent_goal_runs').get().n, 3, 'queue never creates a goal');
assert.equal(store.enqueue('ownerA','ownerA',body).id, note.id);
assert.throws(() => store.enqueue('ownerA','ownerA',{ ...body, message:'Different request' }), /Idempotency/);
assert.throws(() => store.enqueue('ownerB','ownerB',{ ...body, idempotency_key:'different-key' }), /not found/);
assert.throws(() => store.enqueue('ownerA','ownerA',{ ...body, target_id:'ended',idempotency_key:'ended-key' }), /ended/);
assert.throws(() => store.enqueue('ownerA','ownerA',{ ...body,message:'a'.repeat(4001),idempotency_key:'large-key' }), /4000/);
store = createSteeringStore(db); // persisted queue survives a worker/store recreation.
assert.equal(store.consume('ownerB','goal','goal1','tool_result').length,0);
const delivered = store.consume('ownerA','goal','goal1','tool_result:research');
assert.equal(delivered.length, 1);
assert.match(steeringPrompt(delivered), /Do not repeat completed actions/);
assert.equal(store.consume('ownerA','goal','goal1','another_checkpoint').length,0);
assert.equal(store.history('ownerA','goal','goal1')[0].checkpoint,'tool_result:research');
assert.equal(store.active('ownerA','goal','goal1','next_tool').length,1,'delivered guidance persists through subsequent checkpoints');
assert.equal(store.active('ownerB','goal','goal1','next_tool').length,0,'persistent guidance remains owner scoped');
const activeNote=store.active('ownerA','goal','goal1','completion')[0];
store.settle('ownerB',activeNote,{status:'applied',reason:'Not my note'});
assert.equal(store.history('ownerA','goal','goal1')[0].status,'delivered');
store.settle('ownerA',activeNote,{status:'acknowledged',reason:'Deferred to the contracted later step'});
assert.equal(store.active('ownerA','goal','goal1','later_step').length,1);
store.enqueue('ownerA','ownerA',{target_kind:'task',target_id:'1',message:'Focus the summary',idempotency_key:'task-note-1'});
store.close('ownerA','task','1');
assert.equal(store.history('ownerA','task','1')[0].status,'not_applied');
assert.equal(store.consume('ownerA','task','1','late').length,0);
store.enqueue('ownerA','ownerA',{target_kind:'schedule',target_id:'sg1',message:'Add source links',idempotency_key:'schedule-note-1'});
assert.equal(store.consume('ownerA','schedule','sg1','next_fire').length,1);
assert.equal(store.consume('ownerA','schedule','sg1','second_fire').length,0,'guidance is not permanently added to schedule');
store.handoff('ownerA','schedule','sg1','schedule_run','sgr1',['schedule-note-1']);
const fireNote=store.active('ownerA','schedule_run','sgr1','run_completion')[0];
assert.equal(fireNote.message,'Add source links');
store.settle('ownerA',fireNote,{status:'applied',reason:'Source links verified'});
assert.equal(store.history('ownerA','schedule','sg1')[0].status,'applied');
store.handoff('ownerA','schedule','sg1','schedule_run','another-run',[]);
assert.equal(store.active('ownerA','schedule_run','another-run','later_fire').length,0,'resolved schedule guidance never leaks into another fire');
assert.equal(db.prepare('SELECT title FROM scheduled_goals WHERE id=?').get('sg1').title,'Digest');
store.enqueue('ownerA','ownerA',{target_kind:'chat',target_id:'chat1',message:'Short summary',idempotency_key:'chat-note-1'});
db.prepare("UPDATE work_steering SET expires_at=datetime('now','-1 minute') WHERE id=?").run('chat-note-1');
assert.equal(store.consume('ownerA','chat','chat1','tool_result').length,0);
assert.equal(store.history('ownerA','chat','chat1')[0].status,'expired');
assert.throws(() => createSteeringStore(db,{chatActive:()=>false}).enqueue('ownerA','ownerA',{target_kind:'chat',target_id:'chat1',message:'Too late',idempotency_key:'chat-note-2'}), /no longer/);
db.close();
console.log('Steering owner isolation, durable queue, idempotency, safe delivery, no restart and one-fire schedule checks passed');
