import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import {connectorHealthEvidence,liveConnectorHealthEvidence} from '../src/services/connector-health-evidence.js';
const db=new Database(':memory:');
const inventory={apps:[{id:'googledrive',connected:true},{id:'gmail',connected:true},{id:'unrelated_provider',connected:true},{id:'outlook',connected:false}],source:'fixture'};
assert.equal(connectorHealthEvidence('a',inventory,{db}).apps[0].connection_evidence.last_check,null);
db.exec('CREATE TABLE floassist_connector_health(owner_id TEXT,app_id TEXT,state TEXT,checked_at INTEGER)');
db.prepare('INSERT INTO floassist_connector_health VALUES (?,?,?,?)').run('a','google_drive','authorization',1000);
db.prepare('INSERT INTO floassist_connector_health VALUES (?,?,?,?)').run('b','gmail','available',2000);
const r=connectorHealthEvidence('a',inventory,{db});
assert.equal(r.apps[0].connected,true,'registration semantics remain backward compatible');
assert.equal(r.apps[0].connection_evidence.last_check.state,'authorization');
assert.equal(r.apps[0].connection_evidence.last_check.historical,true);
assert.deepEqual(r.apps[0].connection_evidence.live_check.arguments,{action_id:'googledrive.about.get',input:{fields:'kind'}});
assert.equal(r.apps[1].connection_evidence.last_check,null,'no cross-owner observations');
assert.equal(r.apps[1].connection_evidence.live_check.arguments.action_id,'gmail.get_profile','generic provider catalog');
assert.equal(r.apps[2].connection_evidence.live_check,null,'unsupported is not healthy');
assert.equal(r.apps[3].connection_evidence.live_check,null,'not registered');
assert.equal(inventory.apps[0].connection_evidence,undefined,'no mutation');
assert.match(r.health_guidance,/Policy or schema errors do not prove token expiry/);
const calls=[];
const live=await liveConnectorHealthEvidence('a',inventory,{db,probe:async(owner,config)=>{calls.push({owner,config});if(config.action_id==='googledrive.about.get')throw {provider_status:401,message:'invalid_grant'};}});
assert.equal(live.apps[0].connection_evidence.current_check.state,'authorization');
assert.equal(live.apps[1].connection_evidence.current_check.state,'available');
assert.equal(calls.length,2);assert.ok(calls.every(c=>c.owner==='a'));
assert.equal((await liveConnectorHealthEvidence('a',inventory,{db})).apps[0].connection_evidence.current_check.state,'restricted');
const timeout=await liveConnectorHealthEvidence('a',inventory,{db,timeoutMs:5,probe:()=>new Promise(()=>{})});
assert.equal(timeout.apps[0].connection_evidence.current_check.state,'timeout');
assert.equal(timeout.apps[2].connection_evidence.current_check.state,'unsupported');
db.close();console.log('CONNECTOR_HEALTH_EVIDENCE_OK: owner isolation, historical labels, generic live probes, denial, timeout, permissions unchanged, registration compatibility');
