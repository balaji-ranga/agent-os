import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import express from 'express';
const root = mkdtempSync(join(tmpdir(), 'flolah-command-routes-'));
process.env.AGENT_OS_DATA_DIR = root;
process.env.OPENCLAW_DIR = join(root, 'openclaw');
const originalFetch = globalThis.fetch;
let db, server;
try {
  const schema = await import('../src/db/schema.js'); db = schema.initDb();
  const addUser = db.prepare('INSERT INTO platform_users(id,email,password_hash,name,mobile,role,enabled,owner_user_id) VALUES(?,?,?,?,?,?,1,?)');
  addUser.run('owner-a', 'owner-a@test', 'x', 'A', '+6590000001', 'ceo', null);
  addUser.run('owner-b', 'owner-b@test', 'x', 'B', '+6590000002', 'ceo', null);
  addUser.run('employee', 'employee@test', 'x', 'E', '+6590000003', 'org_user', 'owner-a');
  db.prepare("INSERT INTO agents(id,name,openclaw_agent_id,is_coo) VALUES('coo','COO','coo',1),('ungranted','Other','ungranted',0)").run();
  db.prepare("INSERT INTO user_agents(user_id,agent_id,enabled) VALUES('owner-a','coo',1),('employee','coo',1)").run();
  db.prepare("INSERT INTO ceo_agent_channels(id,owner_user_id,agent_id,channel,status) VALUES('wa-a','owner-a','coo','whatsapp','enabled')").run();
  db.prepare("INSERT INTO agent_goal_runs(id,owner_user_id,agent_id,status,title) VALUES('goal-a','owner-a','coo','running','Current research'),('goal-b','owner-b','coo','running','Other tenant private')").run();
  db.prepare("INSERT INTO content_tools_meta(name,display_name,endpoint,method,purpose,enabled,is_builtin) VALUES('command_read_test','Read test','/api/test-read','POST','Synthetic test tool',1,0)").run();
  db.prepare("INSERT INTO agent_tool_grants(agent_id,tool_name) VALUES('coo','command_read_test')").run();
  const skillSvc = await import('../src/services/agent-skills.js');
  const skill = skillSvc.createCompanySkill('owner-a', { name: 'Selected procedure', slug: 'selected-procedure', skill_md: '# Procedure\nUse verified sources.', required_tools: ['command_read_test'] }, 'owner-a');
  const unreadySkill = skillSvc.createCompanySkill('owner-a', { name: 'Blocked procedure', slug: 'blocked-procedure', skill_md: '# Procedure\nUse paid evidence.', required_tools: ['missing_tool'] }, 'owner-a');
  skillSvc.setAgentSkillAssignments('owner-a', 'coo', [{ skill_id: skill.id, auto_select: false }, { skill_id: unreadySkill.id }], 'owner-a');
  const { createSession } = await import('../src/services/auth/session.js');
  const token = createSession('owner-a').token, otherToken = createSession('owner-b').token, employeeToken = createSession('employee').token;
  const { getToolBrokerSecret } = await import('../src/services/tool-scoped-token.js');
  const broker = getToolBrokerSecret();
  const { default: router } = await import('../src/routes/agent-commands.js');
  const app = express(); app.use(express.json()); app.use('/api/agent-commands', router);
  server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)); });
  const base = `http://127.0.0.1:${server.address().port}/api/agent-commands`;
  async function call(path, body, auth = token, headers = {}) {
    const response = await originalFetch(base + path, { method: body ? 'POST' : 'GET', headers: { 'Content-Type': 'application/json', ...(auth ? { Authorization: `Bearer ${auth}` } : {}), ...headers }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, data: await response.json() };
  }
  assert.equal((await call('/coo', null, null)).status, 401);
  assert.equal((await call('/coo', null, otherToken)).status, 404);
  assert.equal((await call('/coo', null, employeeToken)).status, 403);
  assert.equal((await call('/ungranted', null)).status, 404);
  assert.equal((await call('/coo', null)).data.tools.some(t => t.name === 'command_read_test'), true);
  assert.equal((await call('/coo', null)).data.skills.length, 2);
  const selected = await call('/coo', { command: '/flolah skill selected-procedure Cite sources' });
  assert.equal(selected.data.skill.skill_id, skill.id); assert.equal(selected.data.prompt, 'Cite sources');
  assert.equal((await call('/coo', { command: '/flolah skill blocked-procedure' })).status, 409);
  const { validateRequestedAgentSkills } = await import('../src/services/agent-command-runtime.js');
  const refs = validateRequestedAgentSkills('owner-a', 'coo', [skill.id]);
  assert.equal(refs[0].version, 1);
  const instruction = skillSvc.buildAgentSkillRuntimeInstruction('owner-a', 'coo', 'Unrelated prompt', { pinnedRefs: refs });
  assert.equal(instruction.recommended[0].skill_id, skill.id, 'Explicit selection works even with auto_select disabled');
  assert.match(instruction.instruction, /Use verified sources/);
  assert.throws(() => validateRequestedAgentSkills('owner-a', 'coo', ['other-tenant-skill']), /not assigned/);
  assert.throws(() => validateRequestedAgentSkills('owner-a', 'coo', [unreadySkill.id]), /not ready/);
  const active = await call('/coo', { command: '/flolah steer' });
  assert.deepEqual(active.data.targets.map(t => t.id), ['goal-a']);
  const steer = { command: '/flolah steer goal:goal-a Cite primary sources', idempotency_key: 'same-guidance-key' };
  assert.equal((await call('/coo', steer)).data.note.status, 'queued');
  await call('/coo', steer);
  assert.equal(db.prepare('SELECT count(*) n FROM work_steering').get().n, 1);
  assert.equal((await call('/coo', { ...steer, command: '/flolah steer goal:goal-b Cross tenant' })).status, 409);
  assert.equal(db.prepare('SELECT status FROM agent_goal_runs WHERE id=?').get('goal-a').status, 'running');
  assert.equal(db.prepare('SELECT count(*) n FROM agent_goal_runs').get().n, 2, 'Steer never creates work');
  const channel = { channel: 'whatsapp', agent_id: 't-owner-a--coo', account_id: 't-owner-a--coo', session_key: 'agent:t-owner-a--coo:whatsapp:direct:6590000001', sender_id: '6590000001@s.whatsapp.net', from: 'whatsapp:+6590000001', command: '/flolah steer' };
  const brokerHeaders = { 'x-agent-os-tool-broker': broker };
  assert.equal((await call('/channel', channel, null)).status, 401);
  assert.equal((await call('/channel', channel, null, { ...brokerHeaders, 'x-forwarded-for': '127.0.0.1' })).status, 404);
  assert.equal((await call('/channel', channel, null, brokerHeaders)).data.targets.length, 1);
  for (const delta of [{ sender_id: '6590000002' }, { sender_id: '6590000003' }, { account_id: 't-owner-b--coo' }, { session_key: 'agent:t-owner-b--coo:main' }, { from: '123@g.us' }, { session_key: 'agent:t-owner-a--coo:whatsapp:group:123' }]) assert.equal((await call('/channel', { ...channel, ...delta }, null, brokerHeaders)).status, 403);
  db.prepare("UPDATE ceo_agent_channels SET status='disabled' WHERE id='wa-a'").run();
  assert.equal((await call('/channel', channel, null, brokerHeaders)).status, 403);
  let invoked = 0, captured;
  globalThis.fetch = async (url, options) => {
    assert.match(url, /\/api\/tools\/invoke$/); invoked++; captured = options;
    return { ok: false, status: 403, json: async () => ({ error: 'Approval required', approval_token: 'DO-NOT-RETURN' }) };
  };
  const command = { command: '/flolah tool command_read_test {}', idempotency_key: 'stable-command-key' };
  const blocked = await call('/coo', command);
  assert.equal(blocked.data.status, 403); assert(!JSON.stringify(blocked.data).includes('DO-NOT-RETURN'));
  assert.equal(JSON.parse(captured.body).tool_name, 'command_read_test');
  assert(captured.headers.Authorization.startsWith('Bearer '));
  const { lookupOpenClawSessionActor } = await import('../src/services/tool-owner-scope.js');
  assert.equal(lookupOpenClawSessionActor(captured.headers['x-openclaw-session-key']).actorUserId, 'owner-a');
  const replay = await call('/coo', command); assert.equal(replay.data.replayed, true); assert.equal(invoked, 1);
  assert.equal((await call('/coo', { ...command, command: '/tool command_read_test {"owner_user_id":"owner-b"}' })).status, 400);
  assert.equal((await call('/coo', { ...command, command: '/tool command_read_test {"different":true}' })).status, 409);
  db.prepare("UPDATE content_tools_meta SET enabled=0 WHERE name='command_read_test'").run();
  assert.throws(() => validateRequestedAgentSkills('owner-a', 'coo', [skill.id]), /not ready/, 'Disabled required tools block skill selection');
  assert.equal((await call('/coo', { ...command, idempotency_key: 'new-command-key' })).status, 403);
  assert.equal(invoked, 1);
  console.log('Authenticated web/private WhatsApp routes, sender/binding/tenant isolation, canonical lease invocation, approval denial and replay tests passed');
} finally {
  globalThis.fetch = originalFetch;
  if (server) await new Promise(resolve => server.close(resolve));
  db?.close();
  rmSync(root, { recursive: true, force: true });
}
