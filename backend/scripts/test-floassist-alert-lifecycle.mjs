import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import {ALERT_DEFAULTS,alertDecision,validateAlertPreferences} from '../src/services/floassist/alert-policy.js';
import {verifyOrphanClosure} from '../src/services/floassist/reconcile-source.js';
const now=Date.parse('2026-10-27T04:00:00Z'),hour=3600000;
const base={preferences:{...ALERT_DEFAULTS},app:'gmail',now,lastSent:now-hour};
assert.equal(alertDecision(base).send,false);
assert.equal(alertDecision({...base,lastSent:null}).reason,'new_finding');
assert.equal(alertDecision({...base,lastSent:now-25*hour}).send,true);
assert.equal(alertDecision({...base,changed:true}).reason,'verified_deadline_changed');
assert.equal(alertDecision({...base,dueAt:new Date(now-1000).toISOString()}).reason,'deadline_crossed');
assert.equal(alertDecision({...base,preferences:{...ALERT_DEFAULTS,deadline_warning_hours:2},dueAt:new Date(now+1.5*hour).toISOString()}).reason,'deadline_approaching');
assert.equal(alertDecision({...base,preferences:{...ALERT_DEFAULTS,source_realert_hours:{gmail:0}}}).send,true);
assert.equal(alertDecision({...base,preferences:{...ALERT_DEFAULTS,muted_alert_apps:['gmail']},changed:true}).send,false);
assert.equal(alertDecision({...base,sentInDay:3,changed:true}).reason,'task_daily_alert_limit');
assert.equal(alertDecision({...base,dueAt:new Date(now-2*hour).toISOString(),preferences:{...ALERT_DEFAULTS,overdue_realert_hours:1}}).reason,'overdue_reminder');
validateAlertPreferences({...ALERT_DEFAULTS},['gmail']);
for(const patch of [{task_alert_daily_limit:0},{overdue_realert_hours:-1},{deadline_warning_hours:169},{source_realert_hours:{unknown:1}},{muted_alert_apps:['unknown']}])assert.throws(()=>validateAlertPreferences({...ALERT_DEFAULTS,...patch},['gmail']));
const db=new Database(':memory:');
db.exec(`CREATE TABLE floassist_profiles(owner_id TEXT,agent_id TEXT,status TEXT,preferences_json TEXT);
CREATE TABLE floassist_task_tracking(owner_id TEXT,task_id INTEGER,app_id TEXT,source_id TEXT,account_id TEXT,obligation_key TEXT,origin TEXT);
CREATE TABLE kanban_tasks(id INTEGER,owner_user_id TEXT,created_by TEXT,status TEXT);`);
db.prepare('INSERT INTO floassist_profiles VALUES (?,?,?,?)').run('owner','coo','active',JSON.stringify({connectors:['gmail']}));
db.prepare('INSERT INTO floassist_task_tracking VALUES (?,?,?,?,?,?,?)').run('owner',1,'gmail','thread','account','reply','floassist_created');
db.prepare('INSERT INTO kanban_tasks VALUES (?,?,?,?)').run(1,'owner','floassist-tracking','open');
const input={task_id:1,app_id:'gmail',source_id:'thread',account_id:'account',obligation_key:'reply',action:'close_orphan'};
let mode='present',calls=0;
const opts={db,context:{owner:'owner',run:'run'},authorize:async()=>{},execute:async()=>{calls++;if(mode==='missing')throw Object.assign(new Error('missing'),{provider_status:404});if(mode==='denied')throw Object.assign(new Error('denied'),{provider_status:403});return {data:{threadId:mode==='wrong'?'other':'thread',messages:[{labelIds:mode==='trash'?['TRASH']:['INBOX']}]}};}};
assert.equal((await verifyOrphanClosure('owner',input,opts)).action,'clarify');
mode='trash';assert.equal((await verifyOrphanClosure('owner',input,opts)).source_outcome,'deleted');
mode='missing';assert.equal((await verifyOrphanClosure('owner',input,opts)).source_outcome,'deleted');
for(const m of ['denied','wrong']){mode=m;await assert.rejects(verifyOrphanClosure('owner',input,opts));}
const before=calls;
await assert.rejects(verifyOrphanClosure('other',input,opts));
await assert.rejects(verifyOrphanClosure('owner',{...input,source_id:'similar'},opts));
db.prepare('UPDATE kanban_tasks SET created_by=?').run('user');
await assert.rejects(verifyOrphanClosure('owner',input,opts));
assert.equal(calls,before,'Unrelated or mismatched tasks must be rejected before provider access');
assert.equal(db.prepare('SELECT status FROM kanban_tasks').get().status,'open','Verification must not mutate Kanban');
db.close();
console.log('FLOASSIST_ALERT_LIFECYCLE_OK: intervals, escalation, caps, mute, exact-owner reconciliation, provider errors and unrelated-task protection');
