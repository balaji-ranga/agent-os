import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import {initializeFloAssist} from '../src/services/floassist/core.js';
import {tickConnectorMonitor} from '../src/services/floassist/connector-monitor.js';
import {recordFloAssistConnectorHealth as record} from '../src/services/floassist/connector-health.js';
import {tickFloAssistNotifications,floAssistDeliveryGate} from '../src/services/floassist/runtime.js';
const db=new Database(':memory:');initializeFloAssist(db);
db.exec('CREATE TABLE platform_users(id TEXT PRIMARY KEY,enabled INTEGER)');
const prefs={connector_health_enabled:true,connector_health_interval_minutes:60,connectors:['gmail'],responsibilities:[],timezone:'Asia/Singapore',quiet_start:'00:00',quiet_end:'00:00'};
for(const [id,status] of [['a','stopped'],['b','paused'],['c','onboarding']]){
 db.prepare('INSERT INTO platform_users VALUES (?,1)').run(id);
 db.prepare('INSERT INTO floassist_profiles VALUES (?,?,?,?,?,?,?,?)').run(id,'fixture','+6500000000',status,JSON.stringify(prefs),'{}',0,0);
}
const now=Date.now(),seen=[];const check=async(owner)=>{seen.push(owner);record(owner,'gmail','available',{db,now});};
await tickConnectorMonitor({db,now,check,active:()=>false});assert.equal(seen.length,0);
await Promise.all([tickConnectorMonitor({db,now,check}),tickConnectorMonitor({db,now,check})]);
assert.deepEqual(seen.sort(),['a','b']);
assert.equal(db.prepare('SELECT count(*) n FROM floassist_notifications').get().n,0);
await tickConnectorMonitor({db,now:now+1000,check});assert.equal(seen.length,2);
await tickConnectorMonitor({db,now:now+3600000,check});assert.equal(seen.length,4);
record('a','gmail','authorization',{db,now});record('a','gmail','temporary',{db,now});
assert.equal(db.prepare('SELECT count(*) n FROM floassist_notifications').get().n,1,'one failure episode, even if classification changes');
let sent=0;const send=async()=>{sent++;return {ok:true};};
await tickFloAssistNotifications({db,now,send,healthMonitoringActive:()=>false});assert.equal(sent,0);
await tickFloAssistNotifications({db,now,send});await tickFloAssistNotifications({db,now,send});assert.equal(sent,1,'one delivery while task automation is stopped');
record('a','gmail','available',{db,now});await tickFloAssistNotifications({db,now,send});assert.equal(sent,1,'silent recovery');
record('a','gmail','authorization',{db,now});
db.prepare('UPDATE floassist_profiles SET preferences_json=? WHERE owner_id=?').run(JSON.stringify({...prefs,connector_health_enabled:false}),'a');
await tickFloAssistNotifications({db,now,send});assert.equal(sent,1,'owner pause suppresses pending health alert');
assert.equal(record('a','gmail','authorization',{db,now}).ignored,true);
db.prepare("UPDATE platform_users SET enabled=0 WHERE id='b'").run();
await tickConnectorMonitor({db,now:now+7200000,check});assert.equal(seen.length,4);
assert.equal(db.prepare("SELECT status FROM floassist_profiles WHERE owner_id='a'").get().status,'stopped');
db.prepare("UPDATE floassist_profiles SET status='active' WHERE owner_id='a'").run();
db.prepare('INSERT INTO floassist_resources(owner_id,kind,resource_key,resource_id) VALUES (?,?,?,?)').run('a','schedule','briefing','fixture-goal');
for(const text of ['No new tasks.','No tasks pending.','FLOASSIST_NO_UPDATE'])assert.equal(floAssistDeliveryGate({ownerUserId:'a',scheduledGoalId:'fixture-goal',text},db).skip,true);
assert.notEqual(floAssistDeliveryGate({ownerUserId:'a',scheduledGoalId:'fixture-goal',text:'No new tasks. Gmail authorization failed.'},db).reason,'no_update','mixed failure text must remain visible');
db.prepare('INSERT INTO floassist_notifications VALUES (?,?,?,?,?,?,?,?)').run('a:old-empty','a','fixture','No new tasks.','pending',now,now,now+60000);
await tickFloAssistNotifications({db,now,send});
assert.equal(db.prepare("SELECT status FROM floassist_notifications WHERE source_key='a:old-empty'").get().status,'cancelled','legacy queued idle prose cannot leak on resume');
db.close();console.log('CONNECTOR_MONITOR_OK: independent lifecycle, admin/owner pause, disabled owners, durable cadence, concurrent claims, one failure alert, silent healthy/recovery');
