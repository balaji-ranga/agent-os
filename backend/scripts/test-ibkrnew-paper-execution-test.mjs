import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {installTestClock} from '../ibkrnew-event-bridge/test/clock.js';
installTestClock();
process.env.AGENT_OS_DATA_DIR=mkdtempSync(join(tmpdir(),'ibkrnew-paper-test-'));
const {initDb,getDb}=await import('../src/db/schema.js'); initDb();
const s=await import('../src/services/ibkrnew-event-trader.js');
const test=await import('../src/services/ibkrnew-paper-execution-test.js');
const {assertPaperExecutionTestAuthorization}=await import('../src/services/ibkrnew-paper-test-schema.js');
const db=getDb(), owner='paper-smoke-owner';
const cfg=s.ensureIbkrNewDefaults(owner);
const credentials=s.registerBridge(owner),bridge=s.authenticateBridge(credentials.bridge_id,credentials.token);
let sequence=0;
function event(type,payload){return s.ingestBridgeEvent(bridge,{event_id:`smoke-${++sequence}`,sequence,event_type:type,occurred_at:new Date().toISOString(),payload});}
event('bridge.heartbeat',{gateway_connected:true,account_attestation:{status:'verified',environment:'paper',execution_ready:true}});
event('account.snapshot',{eligible_capital_usd:8000,cash_usd:8000,positions:[],open_orders:[]});
event('instrument.profile_refreshed',{symbol:'EEM',security_type:'ETF',average_daily_volume:50000000,assets_under_management_usd:1e11,etf_categories:cfg.universe.filters.etf.categories});
event('market.bar_closed',{symbol:'EEM',security_type:'ETF',market_data_type:1,bid:68.50,ask:68.51,last:68.51,quote_at:new Date().toISOString(),feature_at:new Date().toISOString(),average_daily_volume:50000000});
const body={environment:'paper',confirm_paper_execution_test:true,request_id:'paper-smoke-fixture-20261005',symbol:'EEM'};
const configsBefore=db.prepare('SELECT kind,version,document_json FROM ibkrnew_config_versions WHERE owner_user_id=? ORDER BY kind,version').all(owner);
assert.throws(()=>test.createPaperExecutionTest(owner,{...body,environment:'live'}),/explicit_paper/);
assert.throws(()=>test.createPaperExecutionTest(owner,{...body,symbol:'AAPL'}),/bounded_test/);
assert.throws(()=>test.createPaperExecutionTest(owner,{...body,confirm_paper_execution_test:false}),/explicit_paper/);
assert.throws(()=>test.createPaperExecutionTest('other-owner',body),/verified_paper/);
const bar=db.prepare("SELECT event_id,payload_json FROM ibkrnew_events WHERE event_type='market.bar_closed' AND owner_user_id=?").get(owner);
const original=JSON.parse(bar.payload_json);
db.prepare('UPDATE ibkrnew_events SET payload_json=? WHERE event_id=?').run(JSON.stringify({...original,quote_at:'2026-10-05T13:00:00Z'}),bar.event_id);
assert.throws(()=>test.createPaperExecutionTest(owner,body),/fresh_accepted_quote/);
db.prepare('UPDATE ibkrnew_events SET payload_json=? WHERE event_id=?').run(bar.payload_json,bar.event_id);
db.prepare("UPDATE ibkrnew_execution_modes SET requested_mode='live' WHERE owner_user_id=?").run(owner);
assert.throws(()=>test.createPaperExecutionTest(owner,body),/verified_paper/);
db.prepare("UPDATE ibkrnew_execution_modes SET requested_mode='paper' WHERE owner_user_id=?").run(owner);
db.prepare("UPDATE ibkrnew_account_state SET positions_json=? WHERE owner_user_id=?").run(JSON.stringify([{symbol:'EEM',quantity:1,market_price:68.5}]),owner);
assert.throws(()=>test.createPaperExecutionTest(owner,body),/position_already_exists/);
db.prepare("UPDATE ibkrnew_account_state SET positions_json='[]',cash_usd=1 WHERE owner_user_id=?").run(owner);
assert.throws(()=>test.createPaperExecutionTest(owner,body),/account_cash_or_loss/);
db.prepare('UPDATE ibkrnew_account_state SET cash_usd=8000 WHERE owner_user_id=?').run(owner);
s.pauseIbkrNewGoal(owner,{environment:'paper'});
assert.throws(()=>test.createPaperExecutionTest(owner,body),/paper_opening_blocked/);
s.resumeIbkrNewGoal(owner,{environment:'paper'});
const created=test.createPaperExecutionTest(owner,body);
assert.equal(created.environment,'paper'); assert.equal(created.quantity,1); assert.equal(created.trade.status,'authorized');
assert.ok(created.planned_price_loss_usd<=1); assert.equal(created.excluded_from_goal_profit,true);
assert.equal(db.prepare('SELECT COUNT(*) n FROM ibkrnew_goal_trade_links WHERE authorization_id=?').get(created.authorization_id).n,0);
const a=JSON.parse(db.prepare('SELECT authorization_json FROM ibkrnew_authorizations WHERE authorization_id=?').get(created.authorization_id).authorization_json);
assert.equal(s.validateIbkrNewSubmission(bridge,a.authorization_id).ok,true);
assert.throws(()=>assertPaperExecutionTestAuthorization(db,{...bridge,environment:'live'},a),/invalid_paper/);
assert.throws(()=>assertPaperExecutionTestAuthorization(db,bridge,{...a,authorization_id:'spoof'}),/invalid_paper/);
assert.throws(()=>assertPaperExecutionTestAuthorization(db,bridge,{...a,quantity:2}),/invalid_paper/);
assert.throws(()=>assertPaperExecutionTestAuthorization(db,bridge,{...a,budget:{...a.budget,total_exposure_reserved_usd:200}}),/bound_exceeded/);
assert.equal(test.createPaperExecutionTest(owner,body).test_id,created.test_id);
assert.throws(()=>test.createPaperExecutionTest(owner,{...body,symbol:'TLT'}),/identity_changed/);
assert.throws(()=>test.createPaperExecutionTest(owner,{...body,request_id:'second-paper-test'}),/one_paper_execution_test/);
assert.throws(()=>test.getPaperExecutionTest('other-owner',created.test_id),/not_found/);
assert.throws(()=>test.closePaperExecutionTest(owner,created.test_id,{confirm_paper_test_close:true}),/filled_test/);
const commands=s.claimCommands(bridge,10,2); assert.equal(commands.length,1);
const {signature,expires_at,...command}=commands[0];
assert.equal(signature,crypto.createHmac('sha256',bridge.token_hash).update(JSON.stringify(command)).digest('hex'));
s.acknowledgeCommand(bridge,commands[0].command_id,'submitted');
event('execution.fill',{authorization_id:a.authorization_id,execution_id:'paper-entry',order_role:'entry',side:'BUY',quantity:1,price:68.51});
event('commission.report',{authorization_id:a.authorization_id,execution_id:'paper-entry',commission_usd:1});
assert.equal(test.getPaperExecutionTest(owner,created.test_id).trade.status,'open');
const closing=test.closePaperExecutionTest(owner,created.test_id,{confirm_paper_test_close:true});
assert.ok(closing.exit_authorization_id);
const exit=s.claimCommands(bridge,10,2); assert.equal(exit.length,1); assert.equal(exit[0].type,'IBKRNewManageProtectedExit');
assert.equal(exit[0].authorization.parent_trade_authorization_id,a.authorization_id);
assert.equal(s.validateIbkrNewSubmission(bridge,closing.exit_authorization_id).ok,true);
assert.equal(test.closePaperExecutionTest(owner,created.test_id,{confirm_paper_test_close:true}).exit_authorization_id,closing.exit_authorization_id);
// Only an explicit retry after a definite pre-submission rejection can create
// another close command. Submitted/uncertain operations remain idempotent.
s.acknowledgeCommand(bridge,exit[0].command_id,'rejected');
const retry=test.closePaperExecutionTest(owner,created.test_id,{confirm_paper_test_close:true});
assert.notEqual(retry.exit_authorization_id,closing.exit_authorization_id);
const retryCommands=s.claimCommands(bridge,10,2);assert.equal(retryCommands.length,1);
s.acknowledgeCommand(bridge,retryCommands[0].command_id,'uncertain');
assert.equal(test.closePaperExecutionTest(owner,created.test_id,{confirm_paper_test_close:true}).exit_authorization_id,retry.exit_authorization_id);
event('execution.fill',{authorization_id:a.authorization_id,execution_id:'paper-exit',order_role:'exit',side:'SELL',quantity:1,price:68.52});
event('commission.report',{authorization_id:a.authorization_id,execution_id:'paper-exit',commission_usd:1,realized_pnl_usd:0.01});
const completed=test.getPaperExecutionTest(owner,created.test_id);
assert.equal(completed.trade.status,'closed'); assert.equal(completed.fills.length,2); assert.equal(completed.trade.actual_commission_usd,2);
assert.ok(Math.abs(completed.trade.net_pnl_usd+1.99)<1e-8);
assert.equal(s.getIbkrNewGoalState(owner,{environment:'paper'}).cycle.net_realized_profit_usd,0);
assert.deepEqual(db.prepare('SELECT kind,version,document_json FROM ibkrnew_config_versions WHERE owner_user_id=? ORDER BY kind,version').all(owner),configsBefore);
assert.equal(db.prepare("SELECT COUNT(*) n FROM ibkrnew_authorizations WHERE json_extract(authorization_json,'$.environment')='live'").get().n,0);
const {default:express}=await import('express');
const {default:router}=await import('../src/routes/ibkrnew-paper-execution-test.js');
const app=express(); app.use(express.json());
app.use((req,res,next)=>{if(req.headers['x-test-role'])req.authUser={id:owner,role:req.headers['x-test-role']};next();}); app.use('/tests',router);
const server=app.listen(0,'127.0.0.1'); await new Promise(r=>server.once('listening',r));
