import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root=fs.mkdtempSync(path.join(os.tmpdir(),'flolah-growth-test-'));
process.env.AGENT_OS_DATA_DIR=root;
process.env.NODE_ENV='test';
process.env.SESSION_SECRET='test-session-secret-with-at-least-32-characters';
process.env.TURNSTILE_TEST_BYPASS='1';
const {initDb,getDb}=await import('../src/db/schema.js');initDb();
const p=await import('../src/services/promotions.js');
const m=await import('../src/services/mcp-universe.js');
const db=getDb(),now=new Date().toISOString();
db.prepare(`INSERT INTO platform_users(id,name,email,password_hash,role,enabled,created_at) VALUES ('test-ceo','Test CEO','test-ceo@example.invalid','x','ceo',1,?)`).run(now);
const campaign=p.saveCampaign({name:'Safe campaign',advertiser:'Flolah',disclosure:'Promotional announcement',state:'active',audience:'selected',target_user_ids:['test-ceo'],delivery:'popup',frequency:'once',blocks:[{type:'heading',text:'Hello <script>'},{type:'cta',label:'Read',url:'https://flolah.cloud/docs/'}]},'admin-test');
assert.equal(campaign.blocks[0].text.includes('<'),false,'markup must be removed');
assert.equal(p.eligibleCampaign('other-user'),null,'non-target must not receive campaign');
assert.equal(p.eligibleCampaign('test-ceo')?.id,campaign.id,'target should receive campaign');
assert.equal(p.eligibleCampaign('test-ceo'),null,'once campaign must not repeat');
assert.equal(p.recordPromotionEvent({campaignId:campaign.id,userId:'test-ceo',eventType:'impression',idempotencyKey:'same'}).duplicate,false);
assert.equal(p.recordPromotionEvent({campaignId:campaign.id,userId:'test-ceo',eventType:'impression',idempotencyKey:'same'}).duplicate,true,'events must be idempotent');
const click=p.signedPromotionClick(campaign.id,'test-ceo','https://flolah.cloud/docs/');const decoded=p.resolvePromotionClick(new URL(click).searchParams.get('t'));assert.equal(decoded.u,'test-ceo');assert.equal(decoded.d,'https://flolah.cloud/docs/');
await assert.rejects(()=>m.assertSafePublicUrl('https://127.0.0.1/private'),/blocked network/,'SSRF loopback must be blocked');
assert.equal(await m.verifyTurnstile('test-pass','127.0.0.1'),true,'test-only Turnstile bypass contract');
const fp=m.ipFingerprint('203.0.113.4'),token=m.issueHumanSession(fp);assert.equal(m.verifyHumanSession(token,fp),true);assert.equal(m.verifyHumanSession(token,'other'),false);
m.ensureMcpUniverseTables();
db.prepare(`INSERT INTO mcp_universe_servers(id,identity,name,description,publisher,source_id,status,stale,created_at,updated_at) VALUES ('m1','official:test','Test MCP','Useful server','Publisher','official','approved',0,?,?)`).run(now,now);
assert.equal(m.searchServers({q:'Useful'}).total,1);assert.equal(m.getPublicServer('m1').publisher,'Publisher');
assert.deepEqual(m.aliasRemovalActions({error:{root_cause:[]},status:404}),[],'404 error body must not be treated as an index');
assert.equal(m.aliasRemovalActions({'old-index':{aliases:{[m.MCP_UNIVERSE_ALIAS]:{}}}})[0].remove.index,'old-index');
const sub=m.createSubmission({publisher_name:'Publisher',email:'publisher@example.invalid',name:'Submitted MCP',repository_url:'https://github.com/example/mcp'},fp);assert.equal(sub.status,'submitted');assert.equal(m.moderateSubmission(sub.id,'approved','Reviewed'),true);
db.close();
fs.rmSync(root,{recursive:true,force:true});
console.log('promotions + MCP Universe tests: PASS');
