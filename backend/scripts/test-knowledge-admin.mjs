import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import {knowledgeStore} from '../src/services/knowledge-store.js';
const db=new Database(':memory:');
const store=knowledgeStore(db);
db.exec('CREATE TABLE platform_settings(key TEXT PRIMARY KEY,value TEXT)');
const pause=value=>db.prepare("INSERT OR REPLACE INTO platform_settings VALUES('platform_cron_paused',?)").run(JSON.stringify({knowledge_sync:value}));
const source=store.save('owner',{name:'Schedule test',kind:'content',collections:['generated'],interval_seconds:300});
const before=store.get('owner',source.id);
pause(true);
assert.equal(store.enqueueDue(),0);assert.equal(store.claim(),null);
assert.equal(store.get('owner',source.id).next_sync,before.next_sync);
const queued=store.enqueue('owner',source.id);assert.equal(store.claim(),null);
pause(false);const job=store.claim();assert.equal(job.id,queued.id);assert.equal(job.trigger,'manual');
pause(true);store.finish(job,'g:1',null,{metrics:{checked:2,changed:1,reused:1,deleted:0}});
assert.equal(store.history('owner',source.id)[0].status,'completed');
assert.equal(store.get('owner',source.id).interval_seconds,300);
assert.equal(store.get('owner',source.id).enabled,true);
pause(false);
db.prepare("UPDATE knowledge_sources SET next_sync='2000-01-01' WHERE id=?").run(source.id);
const scheduled=store.claim();assert.equal(scheduled.trigger,'scheduled');store.finish(scheduled,'legacy');
assert.equal(store.history('owner',source.id)[0].changed,null);
db.prepare("UPDATE knowledge_sources SET next_sync='2000-01-01' WHERE id=?").run(source.id);
store.enqueueDue('admin');const admin=store.claim();assert.equal(admin.trigger,'admin');
store.workerHeartbeat();assert.equal(store.adminStats().knowledge_stats.worker_health,'online');
db.exec("UPDATE knowledge_worker_health SET heartbeat_at='2000-01-01'");assert.equal(store.adminStats().knowledge_stats.worker_health,'stale');
assert.equal(store.adminStats().knowledge_stats.totals.changed,1);
assert.equal(store.history('other',source.id).length,0);
console.log('Knowledge Admin harness passed: persistent pause, active completion, source schedule preservation, trigger attribution, counters, heartbeat and isolation.');
