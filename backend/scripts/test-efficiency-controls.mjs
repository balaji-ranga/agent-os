  requests=[];
  await assert.rejects(()=>chatCompletions({ownerUserId:'ceo-a',toolName:'goal_plan_tool_args',endpointPreference:'primary',responseFormat:'json_object',messages:[{role:'user',content:'fixture'}]}),/local-only/);assertions++;
