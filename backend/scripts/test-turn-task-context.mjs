import assert from 'node:assert/strict';
import {resolveTurnTaskPrompt} from '../../openclaw-extensions/agent-os-content-tools/turn-task-context.js';
import {sourceReviewGuidance} from '../../openclaw-extensions/agent-os-content-tools/source-review-turn.js';
const original='Look at real email and calendars and generate week focus areas';
const resolve=(sessionKey,runId,prompt,now=1)=>resolveTurnTaskPrompt({sessionKey,runId,prompt,now});
assert.equal(resolve('a','run-1',original),original);
assert.equal(resolve('a','run-1','Continue after compaction',2),original);
assert.match(sourceReviewGuidance(resolve('a','run-1','Continue',3)),/NOT work priorities/);
assert.equal(resolve('b','run-1','Check device status'),'Check device status');
assert.equal(resolve('a','run-2','Open an app'),'Open an app');
assert.equal(resolve('a','run-2','Continue',4),'Open an app');
assert.equal(resolve('a',null,'New request'),'New request');
assert.equal(resolve(null,'run-2','New request'),'New request');
assert.equal(resolve('a','run-2','Expired context',3600002),'Expired context');
assert.equal(resolve('c','status','What is the status?'),'What is the status?');
assert.equal(resolve('c','status','Recovery finalization'),'What is the status?');
const longTask='Source material. '.repeat(2000)+' Only report verified findings; do not execute actions.';
assert.equal(resolve('long','long-run',longTask),longTask);
assert.equal(resolve('long','long-run','Continue'),longTask,'recovery must not drop instructions after 24k characters');
console.log('TURN_TASK_CONTEXT_OK: recovery retains task contract; new runs, sessions and expiry remain isolated; no permission caching');
