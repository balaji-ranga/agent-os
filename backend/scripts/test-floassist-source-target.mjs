import assert from 'node:assert/strict';
import {rememberSourceReview,sourceReviewParams} from '../../openclaw-extensions/agent-os-content-tools/source-review-turn.js';
import {assertMailboxSourceId,sourceDuplicateRecovery} from '../src/services/floassist/source-read-contract.js';
import {resolveMailboxDay,mailboxDayWindow,gmailWindowQuery} from '../src/services/floassist/source-window.js';
const prompt="Check my gmail for today's emails snd summarize any important";
rememberSourceReview('owner-session',prompt,100);
const bad={id:'floassist_source_read',args:{app_id:'gmail',source_id:'owner@example.test'}};
const corrected=sourceReviewParams('owner-session','tool_call',bad,101);
assert.deepEqual(corrected,{id:'floassist_source_read',args:{app_id:'gmail',review_all:true,relative_day:'today'}});
assert.equal(sourceReviewParams('other-session','tool_call',bad,101),null);
assert.equal(sourceReviewParams('owner-session','tool_call',bad,900101),null);
for(const args of [{source_id:'real-thread'},{kind:'draft'},{task_id:1},{cursor:'fa-page-1'},{next_request:{cursor:'fa-page-1'}}])assert.equal(sourceReviewParams('owner-session','floassist_source_read',{app_id:'gmail',...args},101),null);
rememberSourceReview('explicit',"Summarize today's emails from owner@example.test",100);
assert.equal(sourceReviewParams('explicit','tool_call',bad,101),null);
const now=Date.parse('2026-11-25T00:49:54Z');
const request=resolveMailboxDay(corrected.args,'Asia/Singapore',now);
assert.equal(request.time_min,'2026-11-24T16:00:00.000Z');assert.equal(request.time_max,'2026-11-25T16:00:00.000Z');
assert.match(gmailWindowQuery(request,{now}).query,/after:1795536000 before:1795622400/);
assert.deepEqual(mailboxDayWindow(Date.parse('2026-03-08T18:00:00Z'),'America/New_York'),{time_min:'2026-03-08T05:00:00.000Z',time_max:'2026-03-09T04:00:00.000Z'});
assert.deepEqual(mailboxDayWindow(now,'Asia/Singapore','yesterday'),{time_min:'2026-11-23T16:00:00.000Z',time_max:'2026-11-24T16:00:00.000Z'});
assert.throws(()=>resolveMailboxDay({...corrected.args,time_min:'date'},'Asia/Singapore',now),e=>e.code==='FLOASSIST_SOURCE_WINDOW_REQUIRED');
let failure;
try{assertMailboxSourceId(bad.args);}catch(e){failure=e;}
assert.equal(failure.code,'FLOASSIST_SOURCE_ID_INVALID');assert.equal(failure.next_call.arguments.args.source_id,undefined);
assert.deepEqual(failure.next_action.input,{app_id:'gmail'});
for(const id of ['thread-1','fa-ref-1'])assert.doesNotThrow(()=>assertMailboxSourceId({app_id:'gmail',source_id:id}));
const recovery=sourceDuplicateRecovery({previous_observation:{status:'permanent_error',result:{error:failure.message,code:failure.code,next_call:failure.next_call}}});
assert.match(recovery.error,/No new email read occurred/);assert.deepEqual(recovery.next_call,failure.next_call);
assert.deepEqual(sourceDuplicateRecovery({previous_observation:{status:'ok',result:{content:'private source content'}}}),{});
console.log('FLOASSIST_SOURCE_TARGET_OK: exact failed prompt, owner-local day, DST, explicit filters, selected/task/draft/page isolation, invalid IDs, truthful duplicate recovery');

const {rememberSourceFailure,rewriteSourceFailureReply}=await import('../../openclaw-extensions/agent-os-content-tools/source-failure-reply.js');
const event={sessionKey:'s',runId:'r',payload:{text:'From: COO / Test\n\nAnother request was already processed.',mediaUrl:'keep'}};
rememberSourceFailure('s','r',{ok:false,data:{code:'FLOASSIST_SOURCE_ID_INVALID'}},100);
assert.match(rewriteSourceFailureReply(event,101).payload.text,/No email content was retrieved/);
assert.equal(rewriteSourceFailureReply(event,101).payload.mediaUrl,'keep');
assert.equal(rewriteSourceFailureReply({...event,runId:'other'},101),undefined);
assert.equal(rewriteSourceFailureReply({...event,runId:undefined},101),undefined);
assert.equal(rewriteSourceFailureReply({...event,payload:{text:'Provider authentication failed.'}},101),undefined);
rememberSourceFailure('s','r',{ok:true,data:{content_verified:true}},102);
assert.equal(rewriteSourceFailureReply(event,103),undefined);
console.log('SOURCE_FAILURE_REPLY_OK: exact-run isolation, no raw content retention, successful recovery clears failure');
